function leaderName(p) {




  if (!p.project_leader_id) return "-"




  var u = pool.value.find(function(e) { return e.user_id === p.project_leader_id })




  return u ? u.name : ("#" + p.project_leader_id)




}









function calcProjectWorkdays(p) {









  var stage = p.current_stage || "方案设计"









  var type = p.project_type









  var ratios = type === "大铁"









    ? { "方案设计": 0.02, "初步设计": 0.353, "施工图": 0.55, "施工配合": 0.077 }









    : { "方案设计": 0.12, "初步设计": 0.303, "施工图": 0.50, "施工配合": 0.077 }









  var b = ratios[stage] || 0









  return Math.round((p.planned_man_days || 0) * b)









}



















function statusLabel(status) {









  var map = { planning: "未开始", in_progress: "进行中", design: "进行中", construction: "进行中", stopped: "已暂停", closed: "已完成", completed: "已完成" }









  return map[status] || status || "-"









}



















function calcPlannedWorkdays() {









  var stage = np.value.current_stage || "方案设计"









  var type = np.value.project_type









  var ratios = type === "大铁"









    ? { "方案设计": 0.02, "初步设计": 0.353, "施工图": 0.55, "施工配合": 0.077 }









    : { "方案设计": 0.12, "初步设计": 0.303, "施工图": 0.50, "施工配合": 0.077 }









  var b = ratios[stage] || 0









  return Math.round((np.value.planned_man_days || 0) * b)









}














