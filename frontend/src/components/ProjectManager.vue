async function loadAlloc(pid) {
  try {
    const r = await fetch("/api/performance/workday-alloc/" + pid, { headers: { Authorization: "Bearer " + auth.token } })
    if (!r.ok) return
    const body = await r.json()
    const data = body && body.data ? body.data : (body || {})
    const map = {}
    ;(data.members || []).forEach(function(a) {
      var name = (a.name || "").trim()
      var role = (a.role || "").trim()
      if (!name) return
      var keys = []
      if (role === "专业负责人") keys = ["专业审核", "专业负责人"]
      else if (role === "设计人") keys = ["设计", "设计阶段"]
      else if (role === "复核人") keys = ["复核", "复核阶段"]
      else keys = [role]
      keys.forEach(function(k) { map[name + "|" + k] = a.days || 0 })
    })
    allocDays.value[pid] = map
  } catch(e) { console.error("alloc load err:", e) }
}

function allocDay(pid, m) {
  var map = allocDays.value[pid]
  if (!map) return "-"
  var key = (m.employee_name || "").trim() + "|" + (m.role || "")
  var days = map[key]
  return days === undefined || days === null ? "-" : days
}

